def start_pause(
    conn: sqlite3.Connection, *, kind: str, start: date, end: date | None, note: str | None = None
) -> int:
    cursor = conn.execute(
        "INSERT INTO pause_windows (kind, start_date, end_date, note, created_at) VALUES (?,?,?,?,?)",
        (kind, start.isoformat(), end.isoformat() if end else None, note, _utc_now()),
    )
    return int(cursor.lastrowid)


def end_pause(conn: sqlite3.Connection, *, pause_id: int, end: date | None = None) -> None:
    conn.execute(
        "UPDATE pause_windows SET end_date = ? WHERE id = ?",
        ((end or today()).isoformat(), pause_id),
    )


def load_pauses(conn: sqlite3.Connection) -> tuple[PauseWindow, ...]:
    return tuple(
        PauseWindow(
            kind=row["kind"],
            start_date=date.fromisoformat(row["start_date"]),
            end_date=date.fromisoformat(row["end_date"]) if row["end_date"] else None,
        )
        for row in conn.execute("SELECT * FROM pause_windows ORDER BY start_date")
    )


