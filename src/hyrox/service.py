def cycle_for_week(global_week: int) -> int:
    return max(1, (global_week + 3) // 4)


def record_benchmark(
    conn: sqlite3.Connection,
    *,
    cycle: int,
    test_key: str,
    value: float,
    extra: dict[str, Any] | None = None,
    reference: date | None = None,
) -> None:
    conn.execute(
        """
        INSERT INTO benchmarks (cycle, iso_week, test_key, value, extra_json, recorded_at)
        VALUES (?,?,?,?,?,?)
        ON CONFLICT (cycle, test_key) DO UPDATE SET
            value = excluded.value,
            extra_json = excluded.extra_json,
            recorded_at = excluded.recorded_at
        """,
        (
            cycle,
            iso_week(reference or today()),
            test_key,
            float(value),
            json.dumps(extra or {}),
            _utc_now(),
        ),
    )


def load_benchmark_cycles(conn: sqlite3.Connection) -> tuple[BenchmarkCycle, ...]:
    cycles: dict[int, dict[str, float]] = {}
    for row in conn.execute("SELECT cycle, test_key, value FROM benchmarks ORDER BY cycle"):
        cycles.setdefault(row["cycle"], {})[row["test_key"]] = row["value"]
    return tuple(BenchmarkCycle(cycle=c, values=v) for c, v in sorted(cycles.items()))


