def log_session(
    conn: sqlite3.Connection,
    *,
    slug: str,
    actor: str,
    training_date: date | None = None,
    variant: str | None = None,
    duration_min: int | None = None,
    rpe: int | None = None,
    pain_score: int | None = None,
    pain_location: str | None = None,
    note: str | None = None,
    substituted_from: str | None = None,
    substitution_reason: str | None = None,
    idempotency_key: str | None = None,
    plan: Plan | None = None,
) -> int:
    """Record a completed session and advance the queue.

    `idempotency_key` is generated by the client so an offline completion
    replayed after reconnect cannot double-log. A duplicate key is not an error:
    it returns the original event, which is what makes replay safe.
    """
    plan = plan or load_plan()
    session = plan.session(slug)
    if session is None:
        raise ServiceError(f"unknown session {slug}")

    key = idempotency_key or str(uuid.uuid4())
    existing = conn.execute(
        "SELECT id FROM session_events WHERE idempotency_key = ?", (key,)
    ).fetchone()
    if existing is not None:
        return int(existing["id"])

    stop = active_pain_stop(conn)
    if stop is not None and stop["counts_as"] == session.counts_as:
        raise ServiceError(
            "Training of this kind is paused until your coach reviews the pain you logged."
        )

    if pain_location is not None and pain_location not in PAIN_LOCATIONS:
        raise ServiceError(f"unknown pain location {pain_location!r}")

    advance_from = substituted_from or slug
    day = training_date or today()

    cursor = conn.execute(
        """
        INSERT INTO session_events (
            slug, revision, kind, training_date, completed_at, variant,
            substituted_from, substitution_reason, duration_min, rpe,
            pain_score, pain_location, note, idempotency_key, snapshot_json,
            actor, created_at
        ) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)
        """,
        (
            slug,
            plan.version,
            "swapped" if substituted_from else "completed",
            day.isoformat(),
            _utc_now(),
            variant or session.variant,
            substituted_from,
            substitution_reason,
            duration_min if duration_min is not None else session.cap_minutes,
            rpe,
            pain_score,
            pain_location,
            note,
            key,
            json.dumps(
                {
                    "title": session.title,
                    "kind": session.kind,
                    "counts_as": session.counts_as,
                    "detail": [dict(d) for d in session.detail],
                }
            ),
            actor,
            _utc_now(),
        ),
    )
    _advance_pointer(conn, plan, advance_from)
    return int(cursor.lastrowid)


def skip_session(
    conn: sqlite3.Connection, *, slug: str, actor: str, reason: str, plan: Plan | None = None
) -> int:
    """Record an explicit "not today".

    Deliberately does **not** advance the pointer: nothing is lost, the queue
    simply waits. Its value is that an intentional skip is distinguishable from
    silence, both for the coach and for the reminder logic.
    """
    plan = plan or load_plan()
    session = plan.session(slug)
    if session is None:
        raise ServiceError(f"unknown session {slug}")

    cursor = conn.execute(
        """
        INSERT INTO session_events (
            slug, revision, kind, training_date, completed_at, skip_reason,
            idempotency_key, snapshot_json, actor, created_at
        ) VALUES (?,?,?,?,?,?,?,?,?,?)
        """,
        (
            slug,
            plan.version,
            "skipped",
            today().isoformat(),
            _utc_now(),
            reason,
            str(uuid.uuid4()),
            json.dumps({"title": session.title, "kind": session.kind}),
            actor,
            _utc_now(),
        ),
    )
    return int(cursor.lastrowid)


def void_event(conn: sqlite3.Connection, *, event_id: int, actor: str, plan: Plan | None = None) -> None:
    """Reverse a mis-tap. Append-only: the row stays, marked voided."""
    plan = plan or load_plan()
    row = conn.execute(
        "SELECT * FROM session_events WHERE id = ? AND voided_at IS NULL", (event_id,)
    ).fetchone()
    if row is None:
        raise ServiceError("event not found or already voided")

    conn.execute(
        "UPDATE session_events SET voided_at = ?, voided_by = ? WHERE id = ?",
        (_utc_now(), actor, event_id),
    )

    if row["kind"] in ("completed", "swapped"):
        # Rewind the pointer to whatever this event advanced past.
        rewind_to = row["substituted_from"] or row["slug"]
        session = plan.session(rewind_to)
        progress = db.fetch_progress(conn)
        pointer = progress["pointer_slug"]
        current = plan.session(pointer) if pointer else None
        if session is not None and (current is None or session.ordinal < current.ordinal):
            conn.execute(
                "UPDATE progress SET pointer_slug = ? WHERE id = 1", (session.slug,)
            )


