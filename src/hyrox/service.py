def phase_manual_confirmed(conn: sqlite3.Connection, phase: int) -> bool:
    row = conn.execute(
        "SELECT 1 FROM acknowledgements WHERE kind = 'phase_manual' AND note = ?",
        (str(phase),),
    ).fetchone()
    return row is not None


def confirm_phase_manual(conn: sqlite3.Connection, *, phase: int, actor: str) -> None:
    conn.execute(
        "INSERT INTO acknowledgements (kind, actor, note, created_at) VALUES ('phase_manual',?,?,?)",
        (actor, str(phase), _utc_now()),
    )


def sessions_completed(conn: sqlite3.Connection) -> int:
    row = conn.execute(
        """
        SELECT COUNT(*) AS n FROM session_events
        WHERE voided_at IS NULL AND kind IN ('completed','swapped')
        """
    ).fetchone()
    return int(row["n"])


def phase_progress(conn: sqlite3.Connection, plan: Plan | None = None) -> dict[str, Any]:
    plan = plan or load_plan()
    progress = db.fetch_progress(conn)
    phase = plan.phase(progress["phase"])
    entry = date.fromisoformat(progress["phase_entry_date"])

    outcomes = tuple(
        PriorOutcome(
            iso_week=r["iso_week"],
            floor_met=bool(r["floor_met"]),
            sessions_counted=r["sessions_counted"],
            status=r["status"],
        )
        for r in conn.execute(
            "SELECT * FROM week_outcomes WHERE iso_week >= ? ORDER BY iso_week",
            (iso_week(entry),),
        )
    )

    complete, rows = phase_exit_status(
        plan,
        phase,
        outcomes,
        sessions_completed(conn),
        phase_manual_confirmed(conn, phase.number),
    )
    return {"phase": phase, "complete": complete, "criteria": rows}


def advance_phase_if_ready(conn: sqlite3.Connection, plan: Plan | None = None) -> bool:
    plan = plan or load_plan()
    status = phase_progress(conn, plan)
    if not status["complete"]:
        return False
    phase = status["phase"]
    following = [p for p in plan.phases if p.number > phase.number]
    if not following:
        return False
    conn.execute(
        "UPDATE progress SET phase = ?, phase_entry_date = ? WHERE id = 1",
        (following[0].number, today().isoformat()),
    )
    return True


