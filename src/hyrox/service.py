def week_strip(conn: sqlite3.Connection, reference: date | None = None) -> dict[str, Any]:
    """This week's checkbox row: one cell per day, plus floor progress."""
    day = reference or today()
    start = week_start(day)
    plan = load_plan()
    progress = db.fetch_progress(conn)
    phase = plan.phase(progress["phase"])

    rows = db.events_for_weeks(conn, [iso_week(day)])
    by_day: dict[str, list[dict[str, Any]]] = {}
    for row in rows:
        by_day.setdefault(row["training_date"], []).append(
            {
                "id": row["id"],
                "kind": row["kind"],
                "title": json.loads(row["snapshot_json"]).get("title"),
            }
        )

    days = []
    for offset in range(7):
        d = start + timedelta(days=offset)
        entries = by_day.get(d.isoformat(), [])
        days.append(
            {
                "date": d,
                "label": d.strftime("%a"),
                "is_today": d == day,
                "entries": entries,
                "done": any(e["kind"] in ("completed", "swapped") for e in entries),
                "skipped": any(e["kind"] == "skipped" for e in entries),
            }
        )

    counted = sum(1 for d in days if d["done"])
    return {
        "days": days,
        "counted": counted,
        "floor": phase.floor,
        "target": phase.target,
        "floor_met": counted >= phase.floor,
    }


def dashboard_state(conn: sqlite3.Connection, plan: Plan | None = None) -> dict[str, Any]:
    plan = plan or load_plan()
    progress = db.fetch_progress(conn)
    phase = plan.phase(progress["phase"])
    records = _records(conn, plan)

    rate = training_rate(tuple(records), today(), float(phase.target))
    pointer = progress["pointer_slug"]
    remaining = len(plan.after(pointer)) if pointer else 0

    return {
        "phase": phase,
        "buffer_weeks": progress["buffer_weeks"],
        "baseline_race_date": date.fromisoformat(progress["baseline_race_date"]),
        "projected_race_date": date.fromisoformat(progress["projected_race_date"]),
        "sessions_remaining": remaining,
        "sessions_completed": sessions_completed(conn),
        "rate": round(rate, 2),
        "pain_stop": active_pain_stop(conn),
        "impact_active": impact_substitution_active(conn),
        "swaps_used": swap_allowance_used(conn),
        "swaps_allowed": VOLUNTARY_SWAPS_PER_WEEK,
        "plan_complete": pointer is None,
    }


def benchmark_table(conn: sqlite3.Connection, plan: Plan | None = None) -> dict[str, Any]:
    """Latest cycle against the one before, per test, for the progress bars."""
    plan = plan or load_plan()
    progress = db.fetch_progress(conn)
    tests = plan.battery_for_phase(progress["phase"])
    cycles = load_benchmark_cycles(conn)

    latest = cycles[-1] if cycles else None
    previous = cycles[-2] if len(cycles) > 1 else None

    rows = []
    for test in tests:
        current = latest.values.get(test["key"]) if latest else None
        before = previous.values.get(test["key"]) if previous else None
        change = None
        if current is not None and before:
            change = (current - before) / before * 100
        rows.append(
            {
                "key": test["key"],
                "name": test["name"],
                "unit": test["unit"],
                "protocol": test["protocol"],
                "current": current,
                "previous": before,
                "change_pct": change,
            }
        )
    return {
        "tests": rows,
        "cycle": latest.cycle if latest else None,
        "tested": latest is not None,
    }
