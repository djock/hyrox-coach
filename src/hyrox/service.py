def swap_allowance_used(conn: sqlite3.Connection, reference: date | None = None) -> int:
    day = reference or today()
    label = iso_week(day)
    rows = conn.execute(
        """
        SELECT training_date FROM session_events
        WHERE voided_at IS NULL AND substitution_reason = 'voluntary'
        """
    ).fetchall()
    return sum(1 for r in rows if iso_week(date.fromisoformat(r["training_date"])) == label)


def resolve_swap(
    conn: sqlite3.Connection, *, slug: str, alternative_slug: str, plan: Plan | None = None
) -> PlanSession:
    """Validate a voluntary swap and return the session to be performed.

    Alternatives are authored on the template, never chosen from the queue, so
    there is nothing to defer: he cannot pull an easy session forward from month
    12 and push the hard one back indefinitely.
    """
    plan = plan or load_plan()
    session = plan.session(slug)
    if session is None:
        raise ServiceError(f"unknown session {slug}")

    allowed = {alt.slug for alt in session.alternatives}
    if alternative_slug not in allowed:
        raise ServiceError("That is not a declared alternative for this session.")

    if swap_allowance_used(conn) >= VOLUNTARY_SWAPS_PER_WEEK:
        raise ServiceError("You have already used this week's swap.")

    replacement = plan.session(alternative_slug)
    if replacement is None:
        raise ServiceError(f"unknown alternative {alternative_slug}")
    return replacement


