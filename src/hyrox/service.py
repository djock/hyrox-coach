"""Application services: the queue, logging, swaps, the impact rule, benchmarks.

This is the layer that turns durable rows into the pure engine's inputs and
writes its outputs back. Everything that decides *policy* lives in `engine`;
everything that decides *what happened* lives here.
"""

from __future__ import annotations

