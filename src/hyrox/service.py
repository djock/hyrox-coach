def _records(conn: sqlite3.Connection, plan: Plan) -> list[SessionRecord]:
    records = []
    for row in db.live_events(conn):
        snapshot = json.loads(row["snapshot_json"])
        counts_as = snapshot.get("counts_as")
        if counts_as is None:
            session = plan.session(row["slug"])
            counts_as = session.counts_as if session else "unknown"
        records.append(
            SessionRecord(
                slug=row["slug"],
                kind=row["kind"],
                training_date=date.fromisoformat(row["training_date"]),
                counts_as=counts_as,
                pain_score=row["pain_score"],
                pain_location=row["pain_location"],
            )
        )
    return records


def _prior_outcomes(conn: sqlite3.Connection, before: str) -> tuple[PriorOutcome, ...]:
    rows = conn.execute(
        "SELECT * FROM week_outcomes WHERE iso_week < ? ORDER BY iso_week", (before,)
    ).fetchall()
    return tuple(
        PriorOutcome(
            iso_week=r["iso_week"],
            floor_met=bool(r["floor_met"]),
            sessions_counted=r["sessions_counted"],
            status=r["status"],
        )
        for r in rows
    )


def build_context(
    conn: sqlite3.Connection, monday: date, plan: Plan | None = None
) -> WeekContext:
    plan = plan or load_plan()
    progress = db.fetch_progress(conn)
    label = iso_week(monday)
    start, end = week_start(monday), week_end(monday)

    records = _records(conn, plan)
    events = tuple(r for r in records if start <= r.training_date <= end)
    history = tuple(r for r in records if r.training_date < start)

    pointer = progress["pointer_slug"]
    remaining = len(plan.after(pointer)) if pointer else 0

    last = conn.execute(
        "SELECT * FROM week_outcomes WHERE iso_week < ? ORDER BY iso_week DESC LIMIT 1", (label,)
    ).fetchone()
    previous_projection = date.fromisoformat(
        last["projected_race_date"] if last else progress["projected_race_date"]
    )
    buffer_weeks = last["buffer_after"] if last else progress["buffer_weeks"]

    return WeekContext(
        iso_week=label,
        week_start=start,
        week_end=end,
        phase=plan.phase(progress["phase"]),
        events=events,
        history=history,
        prior_outcomes=_prior_outcomes(conn, label),
        pauses=load_pauses(conn),
        benchmarks=load_benchmark_cycles(conn),
        buffer_weeks=float(buffer_weeks),
        sessions_remaining=remaining,
        baseline_race_date=date.fromisoformat(progress["baseline_race_date"]),
        previous_projection=previous_projection,
        evaluated_on=today(),
    )


def persist_outcome(conn: sqlite3.Connection, outcome: WeekOutcome) -> None:
    """Write once. Outcomes are never recomputed from mutable logs."""
    conn.execute(
        """
        INSERT INTO week_outcomes (
            iso_week, floor_required, sessions_counted, floor_met, status,
            buffer_delta, buffer_after, projected_race_date, detail_json, evaluated_at
        ) VALUES (?,?,?,?,?,?,?,?,?,?)
        ON CONFLICT (iso_week) DO NOTHING
        """,
        (
            outcome.iso_week,
            outcome.floor_required,
            outcome.sessions_counted,
            int(outcome.floor_met),
            outcome.status,
            outcome.buffer_delta,
            outcome.buffer_after,
            outcome.projected_race_date.isoformat(),
            json.dumps(outcome.detail),
            _utc_now(),
        ),
    )
    conn.execute(
        "UPDATE progress SET buffer_weeks = ?, projected_race_date = ? WHERE id = 1",
        (outcome.buffer_after, outcome.projected_race_date.isoformat()),
    )


def evaluate_closed_weeks(
    conn: sqlite3.Connection, reference: date | None = None, plan: Plan | None = None
) -> list[WeekOutcome]:
    """Evaluate every complete week that has no outcome yet.

    Idempotent: running it twice on the same day changes nothing, which is what
    lets it be both a Monday job and a safety net on every request.
    """
    plan = plan or load_plan()
    progress = db.fetch_progress(conn)
    day = reference or today()

    monday = week_start(date.fromisoformat(progress["plan_start"]))
    current_monday = week_start(day)
    outcomes: list[WeekOutcome] = []

    while monday < current_monday:
        label = iso_week(monday)
        exists = conn.execute(
            "SELECT 1 FROM week_outcomes WHERE iso_week = ?", (label,)
        ).fetchone()
        if exists is None:
            outcome = evaluate_week(build_context(conn, monday, plan))
            persist_outcome(conn, outcome)
            outcomes.append(outcome)
        monday += timedelta(days=7)

    return outcomes


