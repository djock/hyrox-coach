# Impact rule
# --------------------------------------------------------------------------


def impact_substitution_active(conn: sqlite3.Connection, reference: date | None = None) -> bool:
    """Two run exposures inside 14 days, same lower-limb location, pain >= 3.

    v1 said "two consecutive logs", which Codex correctly called unsafe -- those
    could be two unrelated sessions weeks apart. Recency and exposure both matter.
    """
    day = reference or today()
    cutoff = day - timedelta(days=IMPACT_WINDOW_DAYS)
    rows = conn.execute(
        """
        SELECT training_date, pain_score, pain_location, snapshot_json
        FROM session_events
        WHERE voided_at IS NULL
          AND kind IN ('completed', 'swapped')
          AND pain_score IS NOT NULL
          AND pain_location IS NOT NULL
        ORDER BY training_date DESC, id DESC
        """
    ).fetchall()

    by_location: dict[str, int] = {}
    for row in rows:
        training_day = date.fromisoformat(row["training_date"])
        if training_day < cutoff or training_day > day:
            continue
        snapshot = json.loads(row["snapshot_json"])
        if snapshot.get("counts_as") != "run_exposure":
            continue
        location = row["pain_location"]
        if location not in LOWER_LIMB or row["pain_score"] < IMPACT_PAIN_THRESHOLD:
            continue
        by_location[location] = by_location.get(location, 0) + 1
        if by_location[location] >= 2:
            return True
    return False


def active_pain_stop(conn: sqlite3.Connection) -> dict[str, Any] | None:
    """An unacknowledged pain report of 5 or more halts that kind of training.

    Holding progression is not enough. An app should not quietly keep
    programming through reported pain, so this blocks logging of the same kind
    until the coach acknowledges it.
    """
    row = conn.execute(
        """
        SELECT e.id, e.pain_score, e.pain_location, e.training_date, e.snapshot_json
        FROM session_events e
        LEFT JOIN acknowledgements a
               ON a.event_id = e.id AND a.kind = 'pain_stop'
        WHERE e.voided_at IS NULL
          AND e.pain_score >= ?
          AND a.id IS NULL
        ORDER BY e.training_date DESC, e.id DESC
        LIMIT 1
        """,
        (PAIN_STOP_THRESHOLD,),
    ).fetchone()
    if row is None:
        return None
    snapshot = json.loads(row["snapshot_json"])
    return {
        "event_id": row["id"],
        "pain_score": row["pain_score"],
        "pain_location": row["pain_location"],
        "training_date": row["training_date"],
        "counts_as": snapshot.get("counts_as"),
    }


def acknowledge_pain_stop(
    conn: sqlite3.Connection, *, event_id: int, actor: str, note: str | None = None
) -> None:
    conn.execute(
        """
        INSERT INTO acknowledgements (kind, event_id, actor, note, created_at)
        VALUES ('pain_stop', ?, ?, ?, ?)
        """,
        (event_id, actor, note, _utc_now()),
    )


